"""Generate a compact, offline geographical index from Aporee coordinates.

Run from repo root with shapely. Natural Earth boundaries are public domain:
https://www.naturalearthdata.com/about/terms-of-use/
Input: geography/states.geojson (Natural Earth 10m admin-1), tmp-locations.json.
Output: app/regions_data.h and geography/report.json. No audio is copied.
"""
from pathlib import Path
import json, struct, unicodedata, zlib, hashlib
import numpy as np
from shapely import points
from shapely.geometry import shape
from shapely.strtree import STRtree

ROOT=Path(__file__).resolve().parents[2]
def ascii_name(s):
    return unicodedata.normalize('NFKD',s).encode('ascii','ignore').decode().replace('"',"'").strip()
def main():
    raw=(ROOT/'geography/states.geojson').read_bytes()
    features=json.loads(raw)['features']
    locations=json.loads((ROOT/'tmp-locations.json').read_text(encoding='utf-8'))
    geoms=[shape(f['geometry']) for f in features]
    xy=points(np.array([[float(r['lng']),float(r['lat'])] for r in locations]))
    hits=STRtree(geoms).query(xy,predicate='intersects')
    assignment={int(i):int(j) for i,j in zip(*hits)}
    groups={}
    for i,j in assignment.items():
        p=features[j]['properties']
        country=ascii_name(p.get('admin') or p.get('geonunit') or 'Other')
        name=ascii_name(p.get('name_en') or p.get('name') or country)
        code=p.get('adm1_code') or p.get('iso_3166_2') or f'{country}/{name}'
        groups.setdefault((country,name,code),[]).append(int(locations[i]['locid']))
    keys=sorted(groups)
    countries=sorted({k[0] for k in keys})
    strings=bytearray(b'Worldwide\0'); offsets={'Worldwide':0}
    def string(s):
        if s not in offsets: offsets[s]=len(strings);strings.extend(s.encode()+b'\0')
        return offsets[s]
    # Index 0 = Worldwide; countries followed by their states, one contiguous tree.
    rows=[(0,0,0,0)]; mapping={}; country_rows=[]
    for country in countries:
        parent=len(rows); rows.append((string(country),0,0,0)); children=[]
        for key in (k for k in keys if k[0]==country):
            rid=len(rows); ids=groups[key];children.append(rid)
            rows.append((string(key[1]),parent,0,len(ids)))
            for locid in ids: mapping[locid]=rid
        rows[parent]=(string(country),0,len(children),sum(rows[j][3] for j in children))
        country_rows.append(parent)
    max_id=max(int(r['locid']) for r in locations)
    (ROOT/'app/build').mkdir(exist_ok=True)
    (ROOT/'app/build/region-expected.bin').write_bytes(b''.join(struct.pack('<H',mapping.get(i,0)) for i in range(max_id+1)))
    page_size=512; blob=bytearray(); pages=[0]
    for start in range(0,max_id+1,page_size):
        block=b''.join(struct.pack('<H',mapping.get(i,0)) for i in range(start,start+page_size))
        c=zlib.compressobj(9,zlib.DEFLATED,-10)
        blob.extend(c.compress(block)+c.flush());pages.append(len(blob))
    def arr(name,data,ctype='uint8_t',width=24):
        return 'static const '+ctype+' '+name+'[] = {\n'+''.join(' '+','.join(map(str,data[i:i+width]))+',\n' for i in range(0,len(data),width))+'};\n'
    out='/* Generated by tools/build_regions.py. Natural Earth: public domain. */\n#pragma once\n#include <stdint.h>\n'
    out+='typedef struct {uint16_t name,parent,children,count;} ap_region_t;\n'
    out+='#define AP_REGION_PAGE_IDS 512u\n#define AP_REGION_MAX_ID '+str(max_id)+'u\n'
    out+=arr('AP_REGION_NAMES',list(strings),'char')
    out+='static const ap_region_t AP_REGIONS[] = {\n'+''.join(' {'+','.join(map(str,r))+'},\n' for r in rows)+'};\n'
    out+=arr('AP_COUNTRIES',country_rows,'uint16_t')
    out+=arr('AP_REGION_PAGES',pages,'uint32_t')+arr('AP_REGION_IDS',list(blob))
    (ROOT/'app/regions_data.h').write_text(out)
    report={'countries':len(countries),'states':len(keys),'locations':len(locations),
        'classified':len(assignment),'unmapped':len(locations)-len(assignment),'max_id':max_id,
        'compressed_membership_bytes':len(blob),'names_bytes':len(strings),
        'estimated_flash_bytes':len(blob)+len(strings)+len(rows)*8+len(pages)*4+len(country_rows)*2,
        'boundary_sha256':hashlib.sha256(raw).hexdigest(),
        'source':'Natural Earth 10m admin-1 (public domain); Aporee public location index',
        'groups':[{'id':i,'name':next(n for n,o in offsets.items() if o==r[0]),'parent':r[1],'count':r[3]} for i,r in enumerate(rows)]}
    (ROOT/'geography/report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2))
    print(json.dumps({k:v for k,v in report.items() if k!='groups'}))
if __name__=='__main__':main()
